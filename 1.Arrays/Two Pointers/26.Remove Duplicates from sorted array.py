#------------------------------------------------------------------------------------------------
#Correct code using single pointer
#Time: O(n) space: O(1) 
#------------------------------------------------------------------------------------------------
nums = [0,0,1,1,1,2,2,3,3,4]
l=0
for r in range(1,len(nums)):
    if nums[l] != nums[r]:
        l+=1
        nums[l]=nums[r]
k=l+1
print(k,nums)